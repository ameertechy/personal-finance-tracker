export function buildCategoriesForUser(userId: string, nowIso: string): CategoryRecord[] {
  return DEFAULT_UAE_EXPENSE_CATEGORIES.map((c, idx) => ({
    id: `cat_${userId.slice(0, 6)}_${idx + 1}`,
    user_id: userId,
    name: c.name,
    slug: c.slug,
    parent_id: null,
    kind: c.kind,
    color: c.color,
    icon: c.icon,
    is_system: true,
    created_at: nowIso,
    updated_at: nowIso,
  }));
}

